@dataclass(frozen=True)
class DecisionConfig:
    """Resolved decision-server settings. Absent URL means the layer is off."""

    url: str
    model: str = DEFAULT_MODEL
    timeout: float = DEFAULT_TIMEOUT
    max_items: int = DEFAULT_MAX_ITEMS
    #: Ceiling for the WHOLE batch. `timeout` alone is per request and additive.
    max_seconds: float = DEFAULT_MAX_SECONDS
    max_consecutive_errors: int = DEFAULT_MAX_CONSECUTIVE_ERRORS

    @classmethod
    def from_env(cls, env: Mapping[str, str] | None = None) -> "DecisionConfig | None":
        """Build a config from the environment, or None when not configured.

        Raises DecisionConfigError when a URL is set but unusable.
        """
        if env is None:
            import os

            env = os.environ

        raw = (env.get("RE_WORKBENCH_DECISION_URL") or "").strip()
        if not raw:
            return None

        return cls(
            url=normalize_url(raw),
            model=(env.get("RE_WORKBENCH_DECISION_MODEL") or DEFAULT_MODEL).strip()
            or DEFAULT_MODEL,
            timeout=_positive_float(
                env.get("RE_WORKBENCH_DECISION_TIMEOUT"),
                DEFAULT_TIMEOUT,
                "RE_WORKBENCH_DECISION_TIMEOUT",
            ),
            max_items=int(
                _positive_float(
                    env.get("RE_WORKBENCH_DECISION_MAX_ITEMS"),
                    DEFAULT_MAX_ITEMS,
                    "RE_WORKBENCH_DECISION_MAX_ITEMS",
                )
            ),
            max_seconds=_positive_float(
                env.get("RE_WORKBENCH_DECISION_MAX_SECONDS"),
                DEFAULT_MAX_SECONDS,
                "RE_WORKBENCH_DECISION_MAX_SECONDS",
            ),
            max_consecutive_errors=int(
                _positive_float(
                    env.get("RE_WORKBENCH_DECISION_MAX_CONSECUTIVE_ERRORS"),
                    DEFAULT_MAX_CONSECUTIVE_ERRORS,
                    "RE_WORKBENCH_DECISION_MAX_CONSECUTIVE_ERRORS",
                )
            ),
        )


def _positive_float(raw: str | None, default: float, label: str) -> float:
    if raw is None or not str(raw).strip():
        return default
    try:
        value = float(str(raw).strip())
    except ValueError as exc:
        raise DecisionConfigError(f"{label} is not a number: {raw!r}") from exc
    if value <= 0:
        raise DecisionConfigError(f"{label} must be positive, got {value!r}")
    return value


def normalize_url(raw: str) -> str:
    """Validate that `raw` points at loopback and return the request URL.

    Evidence assembled from the user's binaries must not leave the machine, so
    anything but 127.0.0.1 / localhost / ::1 is refused outright rather than
    being tried and failing late.
    """
    candidate = raw.strip()
    if "://" not in candidate:
        candidate = "http://" + candidate
    parts = urlparse(candidate)
    if parts.scheme not in ("http", "https"):
        raise DecisionConfigError(
            f"decision URL scheme must be http or https, got {parts.scheme!r}"
        )
    host = (parts.hostname or "").strip().strip("[]").lower()
    if host not in _LOOPBACK_HOSTS:
        raise DecisionConfigError(
            f"decision URL must be loopback (one of {sorted(_LOOPBACK_HOSTS)}), "
            f"got {host!r}. Evidence is not sent off-host."
        )
    path = parts.path or ""
    if path in ("", "/"):
        path = _DEFAULT_PATH
    return urlunparse((parts.scheme, parts.netloc, path, "", parts.query, ""))


# --------------------------------------------------------------------------
# Deterministic evidence templates
# --------------------------------------------------------------------------
#
# ONE place defines the wording. Every item of a batch must go through the same
# function so the only thing that varies between items is the facts: measured,
# the class margin is smaller than the noise introduced by rephrasing.


def estimate_tokens(text: str) -> int:
    """Rough token count for budgeting (4 characters per token)."""
    return math.ceil(len(text) / _CHARS_PER_TOKEN)


#: Every label the templates below can emit, exactly as rendered. Clamping and
#: shape comparison both work off these: counting ";" separators is wrong in
#: both directions (function and string evidence both have five, so a mixed file
#: looks uniform, while one ";" inside a referenced string makes two
#: identically templated items look different).
_FIELD_PREFIXES: tuple[str, ...] = (
    "function ",
    "size ",
    "inbound refs ",
    "imported calls: ",
    "referenced strings: ",
    "string ",
    "section ",
    "offset ",
    "encoding ",
)
_SORTED_PREFIXES = tuple(sorted(_FIELD_PREFIXES, key=len, reverse=True))
_FIELD_SEP = "; "
_LIST_SEP = ", "

#: The shapes the two templates produce, for callers that want to assert it.
FUNCTION_EVIDENCE_SHAPE: tuple[str, ...] = (
    "function",
    "size",
    "inbound refs",
    "imported calls",
    "referenced strings",
)
STRING_EVIDENCE_SHAPE: tuple[str, ...] = (
    "string",
    "section",
    "offset",
    "encoding",
    "inbound refs",
)


def _parse_fields(text: str) -> list[list[str]] | None:
    """Split templated evidence into [prefix, value] pairs on known labels.

    A "; " that is not followed by a known label is part of the value before it,
    so a semicolon inside a string literal does not invent a field. Returns None
    when the text is not templated at all (first segment carries no label).
    """
    fields: list[list[str]] = []
    for segment in text.split(_FIELD_SEP):
        prefix = next((p for p in _SORTED_PREFIXES if segment.startswith(p)), None)
        if prefix is None:
            if not fields:
                return None
            fields[-1][1] += _FIELD_SEP + segment
            continue
        fields.append([prefix, segment[len(prefix) :]])
    return fields


def evidence_shape(text: str) -> tuple[str, ...]:
    """The sequence of template field labels in `text`, or () if untemplated.

    Two items are comparable only when this is equal for both: measured, the
    class margin (0.0015) is smaller than paraphrase noise (0.0041), so a
    missing field is not a detail.
    """
    fields = _parse_fields(str(text))
    if fields is None:
        return ()
    return tuple(prefix.strip().rstrip(":") for prefix, _ in fields)


def clamp_evidence(
    text: str, max_tokens: int = MAX_EVIDENCE_TOKENS
) -> tuple[str, bool]:
    """Fit `text` to the per-item budget WITHOUT losing a field label.

    Returns (text, was_clamped). Cutting the tail off the rendered text is not
    an option: it deletes whole trailing fields, and an item that is missing
    `referenced strings` while the rest of the batch has it is not comparable
    with the batch (measured fact: the class margin is smaller than the spread
    from rewording the evidence). So trailing ELEMENTS of the longest
    list-valued field go first, then the longest remaining value is truncated
    in place, and every label survives. Raises EvidenceTooLong when the labels
    alone do not fit, so the caller refuses the item instead of reshaping it.
    """
    budget = max(1, int(max_tokens)) * _CHARS_PER_TOKEN
    text = str(text)
    if len(text) <= budget:
        return text, False

    fields = _parse_fields(text)
    if fields is None:
        # Not templated evidence: there is no shape to protect, cut the tail.
        return text[: max(1, budget - len(_TRUNCATION_MARKER))] + _TRUNCATION_MARKER, True

    floor = (
        sum(len(prefix) for prefix, _ in fields)
        + len(_FIELD_SEP) * (len(fields) - 1)
        + len(fields)  # one character of value per field, at the very least
    )
    if floor > budget:
        raise EvidenceTooLong(
            f"evidence has {len(fields)} template fields whose labels alone need "
            f"{floor} characters, over the {budget}-character budget "
            f"({max_tokens} tokens); refusing to drop a field label"
        )

    while True:
        rendered = _FIELD_SEP.join(prefix + value for prefix, value in fields)
        if len(rendered) <= budget:
            return rendered, True
        over = len(rendered) - budget
        index = max(range(len(fields)), key=lambda j: (len(fields[j][1]), -j))
        value = fields[index][1]
        elements = value.split(_LIST_SEP)
        if len(elements) > 1:
            # Whole trailing list element: the remaining ones stay readable.
            fields[index][1] = _LIST_SEP.join(elements[:-1])
            continue
        target = max(1, min(len(value) - over, len(value) - 1))
        fields[index][1] = (
            value[: target - len(_TRUNCATION_MARKER)] + _TRUNCATION_MARKER
            if target > len(_TRUNCATION_MARKER)
            else _TRUNCATION_MARKER
        )


def _flatten(text: str) -> str:
    """Collapse whitespace so multi-line input cannot change the template."""
    return re.sub(r"\s+", " ", str(text)).strip()


def _shorten(text: str, limit: int) -> str:
    flat = _flatten(text)
    if len(flat) <= limit:
        return flat
    return flat[: max(0, limit - 1)] + "~"


def _join(values: Iterable[str], count: int, limit: int) -> str:
    items = [_shorten(v, limit) for v in list(values)[:count]]
    return ", ".join(items) if items else "none"


def function_evidence(
    name: str,
    size: int,
    xref_count: int,
    imported_calls: Sequence[str] = (),
    referenced_strings: Sequence[str] = (),
    max_imports: int = 8,
    max_strings: int = 4,
    max_string_chars: int = 40,
    max_tokens: int = MAX_EVIDENCE_TOKENS,
) -> tuple[str, bool]:
    """Render one function as fixed-shape evidence. Returns (text, clamped).

    Field order and wording never vary; empty fields render as "none" so every
    item in a batch has the same shape.
    """
    text = (
        f"function {_shorten(name, 64)}; "
        f"size {int(size)} bytes; "
        f"inbound refs {int(xref_count)}; "
        f"imported calls: {_join(imported_calls, max_imports, 32)}; "
        f"referenced strings: {_join(referenced_strings, max_strings, max_string_chars)}"
    )
    return clamp_evidence(text, max_tokens)


def string_evidence(
    text: str,
    section: str | None = None,
    xref_count: int | None = None,
    offset: int | None = None,
    encoding: str | None = None,
    max_string_chars: int = 240,
    max_tokens: int = MAX_EVIDENCE_TOKENS,
) -> tuple[str, bool]:
    """Render one string literal as fixed-shape evidence. Returns (text, clamped)."""
    rendered = (
        f'string "{_shorten(text, max_string_chars)}"; '
        f"section {_shorten(section, 32) if section else 'unknown'}; "
        f"offset {hex(offset) if offset is not None else 'unknown'}; "
        f"encoding {_shorten(encoding, 16) if encoding else 'unknown'}; "
        f"inbound refs {int(xref_count) if xref_count is not None else 'unknown'}"
    )
    return clamp_evidence(rendered, max_tokens)


