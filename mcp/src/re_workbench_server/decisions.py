"""Optional decision-model ranking layer.

A local System One decision server (one forward pass of a small encoder, not a
language model) can score a piece of evidence against a single yes/no-shaped
question in roughly a second. That is cheap enough to sort a candidate list
with, and nothing more. This module is the client plus the deterministic
evidence templates the rest of the server feeds it.

What the measurements say, and therefore what this module refuses to do
----------------------------------------------------------------------
Every number below was measured against a local server, not assumed.

* Latency grows super-linearly with the length of `state`: 76 tokens took
  0.57 s, 241 tokens 1.61 s, 961 tokens 7.08 s, 3061 tokens 30.6 s. So evidence
  is capped at ~150 tokens per item, the whole batch runs under one wall-clock
  deadline (`DecisionConfig.max_seconds`), and the cost can be read BEFORE
  paying it: `estimate_batch_seconds()` needs no server at all, and the ranking
  tools take `dry_run=True` to return this batch's estimate without asking.
* The returned `noul` value is banded: across 41 measurements every score
  landed inside [0.1774, 0.8384]. An absolute rule such as ">= 0.85 means yes"
  can therefore never fire. This module exposes no thresholds.
* A low score is not a "no". The textbook true positive of an embedded binary
  (96 bytes, 14 inbound refs, only `memcpy`) scored 0.1790 and came last of
  nine candidates. Nothing may be dropped on the strength of a low score.
* An absolute flag rule collapses: ">= 0.80 is suspicious" flagged 7 of 7 files
  in a real set (0.8008-0.8331).
* The class margin is smaller than paraphrase noise: the same facts written as
  four different sentences moved `noul` by 0.0041 while the margin between
  classes was 0.0015. Evidence text must therefore be generated by code from
  one fixed template, identical in shape for every item of a batch. Prose
  written by a language model is not comparable between items.
* Ranking several candidates inside one `choice` call inverted the order (glue
  functions came out top three), so each item gets its own single-condition
  request.
* Role labelling did not generalise (2 of 5 correct on fresh samples; five
  unrelated functions all passed the gate with the same label), so no
  persistent write is ever derived from a score.

The one shape that held up: one small, deterministic, identically templated
piece of evidence per item, one single-condition question, and the result used
only as a *relative ordering key inside the same batch*. In that shape, 4 of 4
real targets landed in the top 5 of an 8-function set, and 8 of 10 strings
ranked correctly. That is a smoke signal, not evidence.
"""

