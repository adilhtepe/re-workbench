# Cost estimation (announced before a batch runs)
# --------------------------------------------------------------------------


def estimate_latency_seconds(tokens: int) -> float:
    """Interpolate the measured latency curve for a state of `tokens` tokens."""
    pts = MEASURED_LATENCY
    if tokens <= pts[0][0]:
        return MIN_REQUEST_SECONDS
    seconds = None
    for (t0, s0), (t1, s1) in zip(pts, pts[1:]):
        if tokens <= t1:
            frac = (tokens - t0) / (t1 - t0)
            seconds = s0 + frac * (s1 - s0)
            break
    if seconds is None:
        # Beyond the measured range: extrapolate on the last measured slope.
        (t0, s0), (t1, s1) = pts[-2], pts[-1]
        seconds = s1 + (tokens - t1) * (s1 - s0) / (t1 - t0)
    return round(max(MIN_REQUEST_SECONDS, seconds), 3)


def estimate_batch_seconds(item_count: int, tokens_per_item: int = MAX_EVIDENCE_TOKENS) -> float:
    """Expected wall-clock cost of scoring `item_count` items, one request each."""
    return round(max(0, item_count) * estimate_latency_seconds(tokens_per_item), 2)


