class SystemOneClient:
    """Minimal System One client over urllib. No third-party dependency."""

    def __init__(self, config: DecisionConfig) -> None:
        # Re-validate on construction: no code path may reach a non-loopback
        # host, however the config was built.
        self.config = DecisionConfig(
            url=normalize_url(config.url),
            model=config.model,
            timeout=config.timeout,
            max_items=config.max_items,
        )
        # Explicitly proxy-free: a loopback request must not be routed out.
        self._opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))

    def ask(
        self,
        state: str,
        question_id: str,
        instructions: str,
        criteria: Any | None = None,
        timeout: float | None = None,
    ) -> dict[str, Any]:
        """Ask ONE single-condition question about ONE state.

        Returns {"score": float, "raw": float|None, "usage": {...},
        "elapsed_s": float}. Raises DecisionUnavailable on any transport or
        protocol failure.
        """
        question: dict[str, Any] = {
            "type": QUESTION_TYPE,
            "instructions": instructions,
        }
        if criteria:
            question["criteria"] = criteria
        payload = {
            "model": self.config.model,
            "state": state,
            "questions": {question_id: question},
        }
        body = json.dumps(payload).encode("utf-8")
        req = urllib.request.Request(
            self.config.url,
            data=body,
            headers={"Content-Type": "application/json", "Accept": "application/json"},
            method="POST",
        )
        started = time.monotonic()
        try:
            with self._opener.open(req, timeout=timeout or self.config.timeout) as resp:
                raw = resp.read()
        except urllib.error.HTTPError as exc:
            detail = ""
            try:
                detail = exc.read().decode("utf-8", "replace")[:400]
            except Exception:
                pass
            raise DecisionUnavailable(
                f"decision server returned HTTP {exc.code}: {detail or exc.reason}"
            ) from exc
        except (urllib.error.URLError, OSError) as exc:
            raise DecisionUnavailable(f"decision server unreachable: {exc}") from exc
        elapsed = time.monotonic() - started

        try:
            data = json.loads(raw.decode("utf-8"))
        except (ValueError, UnicodeDecodeError) as exc:
            raise DecisionUnavailable(f"decision server sent non-JSON: {exc}") from exc

        answers = data.get("answers")
        if not isinstance(answers, dict) or question_id not in answers:
            raise DecisionUnavailable(
                f"decision server answer missing question {question_id!r}"
            )
        answer = answers[question_id] or {}
        score = answer.get(QUESTION_TYPE)
        if not isinstance(score, (int, float)):
            raise DecisionUnavailable(
                f"decision server answer has no numeric {QUESTION_TYPE}: {answer!r}"
            )
        return {
            "score": float(score),
            "raw": answer.get(f"{QUESTION_TYPE}_raw"),
            "model": data.get("model"),
            "usage": data.get("usage") or {},
            "elapsed_s": round(elapsed, 3),
        }


def unavailable(reason: str, config: DecisionConfig | None = None) -> dict[str, Any]:
    """The standard 'no decision server' envelope, shared by every caller."""
    return {
        "status": "unavailable",
        "reason": reason,
        "model": config.model if config else None,
        "url": config.url if config else None,
        "template_version": EVIDENCE_TEMPLATE_VERSION,
        "caveats": list(CAVEATS),
    }


def score_items(
    items: Sequence[Mapping[str, Any]],
    question_id: str,
    instructions: str,
    criteria: Any | None = None,
    config: DecisionConfig | None = None,
    env: Mapping[str, str] | None = None,
) -> dict[str, Any]:
    """Score each item's evidence with its OWN request.

    `items` is a sequence of mappings with at least "key" and "evidence".
    Measured: ranking several candidates inside one call inverts the order, so
    batching into a single request is not an option.

    Never raises for an unreachable server: returns status "unavailable" so the
    caller can fall back to its deterministic order and still return every item.
    """
    try:
        cfg = config or DecisionConfig.from_env(env)
    except DecisionConfigError as exc:
        return unavailable(str(exc))
    if cfg is None:
        return unavailable(
            "RE_WORKBENCH_DECISION_URL is not set; decision ranking is off"
        )

    try:
        client = SystemOneClient(cfg)
    except DecisionConfigError as exc:
        return unavailable(str(exc), cfg)

    scores: dict[str, dict[str, Any]] = {}
    errors: list[dict[str, str]] = []
    in_tokens = out_tokens = requests = clamped = 0
    served_model: str | None = None
    budget = cfg.max_items
    started = time.monotonic()

    for index, item in enumerate(items):
        key = str(item.get("key", index))
        evidence, was_clamped = clamp_evidence(str(item.get("evidence", "")))
        if was_clamped:
            clamped += 1
        if index >= budget:
            scores[key] = {
                "score": None,
                "evidence": evidence,
                "clamped": was_clamped,
                "error": f"not scored: max_items={budget} reached",
            }
            continue
        try:
            answer = client.ask(evidence, question_id, instructions, criteria)
        except DecisionUnavailable as exc:
            message = str(exc)
            errors.append({"key": key, "error": message})
            scores[key] = {
                "score": None,
                "evidence": evidence,
                "clamped": was_clamped,
                "error": message,
            }
            continue
        requests += 1
        served_model = served_model or answer.get("model")
        usage = answer.get("usage") or {}
        in_tokens += int(usage.get("input_tokens") or 0)
        out_tokens += int(usage.get("output_tokens") or 0)
        scores[key] = {
            "score": answer["score"],
            "raw": answer.get("raw"),
            "evidence": evidence,
            "clamped": was_clamped,
            "elapsed_s": answer.get("elapsed_s"),
        }

    total = len(items)
    if requests == 0 and total:
        envelope = unavailable(
            errors[0]["error"] if errors else "no item could be scored", cfg
        )
        envelope["requested"] = total
        envelope["scored"] = 0
        envelope["scores"] = scores
        return envelope

    return {
        "status": "ok" if requests == total else "partial",
        "model": served_model or cfg.model,
        "url": cfg.url,
        "template_version": EVIDENCE_TEMPLATE_VERSION,
        "question_id": question_id,
        "instructions": instructions,
        "requested": total,
        "scored": requests,
        "clamped_evidence": clamped,
        "max_items": budget,
        "errors": errors,
        "usage": {
            "requests": requests,
            "input_tokens": in_tokens,
            "output_tokens": out_tokens,
        },
        "elapsed_s": round(time.monotonic() - started, 2),
        "scores": scores,
        "caveats": list(CAVEATS),
    }


def probe(
    config: DecisionConfig | None = None, env: Mapping[str, str] | None = None
) -> dict[str, Any]:
    """Report whether the decision server is configured and reachable."""
    try:
        cfg = config or DecisionConfig.from_env(env)
    except DecisionConfigError as exc:
        return {
            "status": "unavailable",
            "configured": True,
            "reachable": False,
            "reason": str(exc),
        }
    if cfg is None:
        return {
            "status": "unavailable",
            "configured": False,
            "reachable": False,
            "reason": "RE_WORKBENCH_DECISION_URL is not set; decision ranking is off",
        }
    try:
        answer = SystemOneClient(cfg).ask(
            "probe", "probe", "Is the decision server answering?"
        )
    except (DecisionUnavailable, DecisionConfigError) as exc:
        return {
            "status": "unavailable",
            "configured": True,
            "reachable": False,
            "url": cfg.url,
            "model": cfg.model,
            "reason": str(exc),
        }
    return {
        "status": "ok",
        "configured": True,
        "reachable": True,
        "url": cfg.url,
        "model": answer.get("model") or cfg.model,
        "probe_score": answer["score"],
        "probe_elapsed_s": answer.get("elapsed_s"),
        "timeout_s": cfg.timeout,
        "max_items": cfg.max_items,
    }
