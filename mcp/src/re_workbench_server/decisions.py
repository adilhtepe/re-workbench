#: Named, boring patterns for the classic string classes of an embedded image.
#: This runs before any scoring and is pure regex: the decision model never
#: decides what is a candidate, it only orders the candidates.
DEFAULT_STRING_PATTERNS: tuple[tuple[str, str], ...] = (
    ("url", r"\b(?:https?|ftps?|tftp|telnet|ws|wss)://"),
    ("ipv4", r"\b(?:\d{1,3}\.){3}\d{1,3}\b"),
    ("host", r"(?i:\b[a-z0-9][a-z0-9.-]*\.(?:com|net|org|io|cn|ru|local|lan)\b)"),
    # \b is useless here: in "wpa_psk" the underscore is a word character, so
    # \bpsk\b never matches. These classes use explicit alphanumeric
    # lookarounds so underscore- and dash-joined config keys are caught.
    ("credential", r"(?i:(?<![a-z0-9])(?:pass|passwd|password|pwd|secret|token|api[_-]?key|credential|login|auth|psk|pin)(?![a-z0-9]))"),
    ("key_material", r"-----BEGIN|ssh-(?:rsa|ed25519)|PRIVATE KEY"),
    ("unix_path", r"(?:^|[\s\"'=])/(?:etc|bin|sbin|usr|var|tmp|dev|proc|mnt|root|home)/"),
    ("windows_path", r"[A-Za-z]:\\|\\\\[A-Za-z0-9_.-]+\\"),
    ("command", r"(?i:(?<![a-z0-9])(?:system|popen|exec|busybox|iptables|wget|curl|telnetd|dropbear)(?![a-z0-9])|/bin/(?:sh|ash|bash|busybox)|sh -c|(?<![a-z0-9])nc -)"),
    ("config_key", r"(?i:(?<![a-z0-9])(?:bootcmd|firmware|serialnumber|mac(?:addr)?|ssid|wpa|psk|admin|root)(?![a-z0-9]))"),
    ("format_string", r"%(?:[0-9.*+-]*)(?:s|d|u|x|X|p|ll?[dux])"),
)


def default_string_pattern() -> str:
    """One alternation of DEFAULT_STRING_PATTERNS, for reporting and reuse."""
    return "|".join(f"(?:{pat})" for _, pat in DEFAULT_STRING_PATTERNS)


def classify_string(text: str) -> list[str]:
    """Which default pattern classes `text` matches (deterministic, regex only)."""
    return [name for name, pat in DEFAULT_STRING_PATTERNS if re.search(pat, text)]


