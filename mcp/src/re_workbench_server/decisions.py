# --------------------------------------------------------------------------
# Constants driven by the measurements in the module docstring
# --------------------------------------------------------------------------

#: Bump whenever a template below changes shape. Scores produced under
#: different versions are not comparable, so the version travels with results.
EVIDENCE_TEMPLATE_VERSION = "ev1"

DEFAULT_MODEL = "von-1.3"
DEFAULT_TIMEOUT = 60.0
DEFAULT_MAX_ITEMS = 150

#: Wall-clock ceiling for one WHOLE batch, not one request. Per-request
#: timeouts are additive: measured, five items against a sleeping server with a
#: 1 s per-request timeout took 5.03 s, so the defaults alone (150 items x 60 s)
#: would let a single tool call block for 2.5 hours. Every batch therefore runs
#: under this deadline and reports when it stopped early.
DEFAULT_MAX_SECONDS = 300.0

#: Stop asking after this many requests fail back to back: once the server has
#: gone away, the rest of the batch only buys more timeouts.
DEFAULT_MAX_CONSECUTIVE_ERRORS = 5

#: Per-item evidence budget. Beyond this, latency stops being worth it.
MAX_EVIDENCE_TOKENS = 150
_CHARS_PER_TOKEN = 4

#: Truncation is marked inside the field whose value was cut, never by appending
#: to the rendered text: a trailing marker would itself make a clamped item a
#: different shape from an unclamped one. The `clamped` flag carries the signal.
_TRUNCATION_MARKER = "~"

#: The only scores the wire protocol may produce. Measured band is
#: [0.1774, 0.8384]; anything outside [0, 1] is a protocol error, not a score.
SCORE_MIN = 0.0
SCORE_MAX = 1.0

#: The wire type name of a yes/no-shaped question. Measured: {"type":
#: "boolean"} is rejected with 422 "Unknown question type" by both the decision
#: server and its compatibility layer, so the native name is used directly.
QUESTION_TYPE = "noul"

_LOOPBACK_HOSTS = frozenset({"127.0.0.1", "localhost", "::1"})
_DEFAULT_PATH = "/v1/systemone"

#: (state tokens, seconds) pairs measured on the local server. Used only to
#: tell the caller what a batch will cost before it runs.
MEASURED_LATENCY: tuple[tuple[int, float], ...] = (
    (76, 0.57),
    (241, 1.61),
    (961, 7.08),
    (3061, 30.6),
)

#: Below the shortest measured state, per-request overhead dominates and the
#: curve stops applying. Measured on real batches of this server's own evidence
#: (~30 tokens per item): 8 items in 7.73 s and 9 items in 7.59 s, i.e. ~0.9 s
#: per request. Estimates are floored here so a batch is never under-announced.
MIN_REQUEST_SECONDS = 0.9

CAVEATS: tuple[str, ...] = (
    "Ranking only: no item is dropped, filtered or hidden, and the tool returns "
    "no verdict of any kind.",
    "A low score is not a negative answer. A measured true positive (96 bytes, "
    "14 inbound refs, only memcpy) scored 0.1790 and ranked last of nine.",
    "Scores are banded: 41 measurements all fell inside [0.1774, 0.8384], so "
    "absolute thresholds cannot fire and none are applied.",
    "Scores are comparable only against the other items of the same batch, "
    f"produced by the same evidence template ({EVIDENCE_TEMPLATE_VERSION}).",
    "The class margin measured smaller than paraphrase noise (0.0015 vs "
    "0.0041), so treat small differences in rank as noise.",
    "Calibrate the question against your own labelled data with eval/calibrate.py "
    "before giving any weight to the order.",
)


class DecisionConfigError(ValueError):
    """The decision server is configured, but configured wrongly."""


class DecisionUnavailable(RuntimeError):
    """The decision server is not configured or could not be reached."""


class EvidenceTooLong(ValueError):
    """Evidence cannot be fitted to the budget without dropping a field label.

    Measured fact 5 makes the field shape part of the comparison: an item whose
    template fields are not all present is not comparable with the rest of the
    batch, so it is refused rather than silently reshaped.
    """


