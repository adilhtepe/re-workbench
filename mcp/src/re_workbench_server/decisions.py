# --------------------------------------------------------------------------
# Constants driven by the measurements in the module docstring
# --------------------------------------------------------------------------

#: Bump whenever a template below changes shape. Scores produced under
#: different versions are not comparable, so the version travels with results.
EVIDENCE_TEMPLATE_VERSION = "ev1"

DEFAULT_MODEL = "von-1.3"
DEFAULT_TIMEOUT = 60.0
DEFAULT_MAX_ITEMS = 150

#: Per-item evidence budget. Beyond this, latency stops being worth it.
MAX_EVIDENCE_TOKENS = 150
_CHARS_PER_TOKEN = 4
_CLAMP_MARKER = " [clamped]"

#: The wire type name of a yes/no-shaped question. Measured: {"type":
#: "boolean"} is rejected with 422 "Unknown question type" by both the decision
#: server and its compatibility layer, so the native name is used directly.
QUESTION_TYPE = "noul"

_LOOPBACK_HOSTS = frozenset({"127.0.0.1", "localhost", "::1"})
_DEFAULT_PATH = "/v1/systemone"

#: (state tokens, seconds) pairs measured on the local server. Used only to
#: tell the caller what a batch will cost before it runs.
MEASURED_LATENCY: tuple[tuple[int, float], ...] = (
    (76, 0.57),
    (241, 1.61),
    (961, 7.08),
    (3061, 30.6),
)

#: Below the shortest measured state, per-request overhead dominates and the
#: curve stops applying. Measured on real batches of this server's own evidence
#: (~30 tokens per item): 8 items in 7.73 s and 9 items in 7.59 s, i.e. ~0.9 s
#: per request. Estimates are floored here so a batch is never under-announced.
MIN_REQUEST_SECONDS = 0.9

CAVEATS: tuple[str, ...] = (
    "Ranking only: no item is dropped, filtered or hidden, and the tool returns "
    "no verdict of any kind.",
    "A low score is not a negative answer. A measured true positive (96 bytes, "
    "14 inbound refs, only memcpy) scored 0.1790 and ranked last of nine.",
    "Scores are banded: 41 measurements all fell inside [0.1774, 0.8384], so "
    "absolute thresholds cannot fire and none are applied.",
    "Scores are comparable only against the other items of the same batch, "
    f"produced by the same evidence template ({EVIDENCE_TEMPLATE_VERSION}).",
    "The class margin measured smaller than paraphrase noise (0.0015 vs "
    "0.0041), so treat small differences in rank as noise.",
    "Calibrate the question against your own labelled data with eval/calibrate.py "
    "before giving any weight to the order.",
)


class DecisionConfigError(ValueError):
    """The decision server is configured, but configured wrongly."""


class DecisionUnavailable(RuntimeError):
    """The decision server is not configured or could not be reached."""


# --------------------------------------------------------------------------
# Configuration
# --------------------------------------------------------------------------


@dataclass(frozen=True)
class DecisionConfig:
    """Resolved decision-server settings. Absent URL means the layer is off."""

    url: str
    model: str = DEFAULT_MODEL
    timeout: float = DEFAULT_TIMEOUT
    max_items: int = DEFAULT_MAX_ITEMS

    @classmethod
    def from_env(cls, env: Mapping[str, str] | None = None) -> "DecisionConfig | None":
        """Build a config from the environment, or None when not configured.

        Raises DecisionConfigError when a URL is set but unusable.
        """
        if env is None:
            import os

            env = os.environ

        raw = (env.get("RE_WORKBENCH_DECISION_URL") or "").strip()
        if not raw:
            return None

        return cls(
            url=normalize_url(raw),
            model=(env.get("RE_WORKBENCH_DECISION_MODEL") or DEFAULT_MODEL).strip()
            or DEFAULT_MODEL,
            timeout=_positive_float(
                env.get("RE_WORKBENCH_DECISION_TIMEOUT"),
                DEFAULT_TIMEOUT,
                "RE_WORKBENCH_DECISION_TIMEOUT",
            ),
            max_items=int(
                _positive_float(
                    env.get("RE_WORKBENCH_DECISION_MAX_ITEMS"),
                    DEFAULT_MAX_ITEMS,
                    "RE_WORKBENCH_DECISION_MAX_ITEMS",
                )
            ),
        )


def _positive_float(raw: str | None, default: float, label: str) -> float:
    if raw is None or not str(raw).strip():
        return default
    try:
        value = float(str(raw).strip())
    except ValueError as exc:
        raise DecisionConfigError(f"{label} is not a number: {raw!r}") from exc
    if value <= 0:
        raise DecisionConfigError(f"{label} must be positive, got {value!r}")
    return value


def normalize_url(raw: str) -> str:
    """Validate that `raw` points at loopback and return the request URL.

    Evidence assembled from the user's binaries must not leave the machine, so
    anything but 127.0.0.1 / localhost / ::1 is refused outright rather than
    being tried and failing late.
    """
    candidate = raw.strip()
    if "://" not in candidate:
        candidate = "http://" + candidate
    parts = urlparse(candidate)
    if parts.scheme not in ("http", "https"):
        raise DecisionConfigError(
            f"decision URL scheme must be http or https, got {parts.scheme!r}"
        )
    host = (parts.hostname or "").strip().strip("[]").lower()
    if host not in _LOOPBACK_HOSTS:
        raise DecisionConfigError(
            f"decision URL must be loopback (one of {sorted(_LOOPBACK_HOSTS)}), "
            f"got {host!r}. Evidence is not sent off-host."
        )
    path = parts.path or ""
    if path in ("", "/"):
        path = _DEFAULT_PATH
    return urlunparse((parts.scheme, parts.netloc, path, "", parts.query, ""))


# --------------------------------------------------------------------------
# Deterministic evidence templates
# --------------------------------------------------------------------------
#
# ONE place defines the wording. Every item of a batch must go through the same
# function so the only thing that varies between items is the facts: measured,
# the class margin is smaller than the noise introduced by rephrasing.


def estimate_tokens(text: str) -> int:
    """Rough token count for budgeting (4 characters per token)."""
    return math.ceil(len(text) / _CHARS_PER_TOKEN)


def clamp_evidence(
    text: str, max_tokens: int = MAX_EVIDENCE_TOKENS
) -> tuple[str, bool]:
    """Cut `text` down to the per-item budget. Returns (text, was_clamped)."""
    budget = max(1, int(max_tokens)) * _CHARS_PER_TOKEN
    if len(text) <= budget:
        return text, False
    keep = max(0, budget - len(_CLAMP_MARKER))
    return text[:keep] + _CLAMP_MARKER, True


def _flatten(text: str) -> str:
    """Collapse whitespace so multi-line input cannot change the template."""
    return re.sub(r"\s+", " ", str(text)).strip()


def _shorten(text: str, limit: int) -> str:
    flat = _flatten(text)
    if len(flat) <= limit:
        return flat
    return flat[: max(0, limit - 1)] + "~"


def _join(values: Iterable[str], count: int, limit: int) -> str:
    items = [_shorten(v, limit) for v in list(values)[:count]]
    return ", ".join(items) if items else "none"


def function_evidence(
    name: str,
    size: int,
    xref_count: int,
    imported_calls: Sequence[str] = (),
    referenced_strings: Sequence[str] = (),
    max_imports: int = 8,
    max_strings: int = 4,
    max_string_chars: int = 40,
    max_tokens: int = MAX_EVIDENCE_TOKENS,
) -> tuple[str, bool]:
    """Render one function as fixed-shape evidence. Returns (text, clamped).

    Field order and wording never vary; empty fields render as "none" so every
    item in a batch has the same shape.
    """
    text = (
        f"function {_shorten(name, 64)}; "
        f"size {int(size)} bytes; "
        f"inbound refs {int(xref_count)}; "
        f"imported calls: {_join(imported_calls, max_imports, 32)}; "
        f"referenced strings: {_join(referenced_strings, max_strings, max_string_chars)}"
    )
    return clamp_evidence(text, max_tokens)


def string_evidence(
    text: str,
    section: str | None = None,
    xref_count: int | None = None,
    offset: int | None = None,
    encoding: str | None = None,
    max_string_chars: int = 240,
    max_tokens: int = MAX_EVIDENCE_TOKENS,
) -> tuple[str, bool]:
    """Render one string literal as fixed-shape evidence. Returns (text, clamped)."""
    rendered = (
        f'string "{_shorten(text, max_string_chars)}"; '
        f"section {_shorten(section, 32) if section else 'unknown'}; "
        f"offset {hex(offset) if offset is not None else 'unknown'}; "
        f"encoding {_shorten(encoding, 16) if encoding else 'unknown'}; "
        f"inbound refs {int(xref_count) if xref_count is not None else 'unknown'}"
    )
    return clamp_evidence(rendered, max_tokens)


# --------------------------------------------------------------------------
# Deterministic pre-filter for strings
# --------------------------------------------------------------------------

#: Named, boring patterns for the classic string classes of an embedded image.
#: This runs before any scoring and is pure regex: the decision model never
#: decides what is a candidate, it only orders the candidates.
DEFAULT_STRING_PATTERNS: tuple[tuple[str, str], ...] = (
    ("url", r"\b(?:https?|ftps?|tftp|telnet|ws|wss)://"),
    ("ipv4", r"\b(?:\d{1,3}\.){3}\d{1,3}\b"),
    ("host", r"(?i:\b[a-z0-9][a-z0-9.-]*\.(?:com|net|org|io|cn|ru|local|lan)\b)"),
    # \b is useless here: in "wpa_psk" the underscore is a word character, so
    # \bpsk\b never matches. These classes use explicit alphanumeric
    # lookarounds so underscore- and dash-joined config keys are caught.
    ("credential", r"(?i:(?<![a-z0-9])(?:pass|passwd|password|pwd|secret|token|api[_-]?key|credential|login|auth|psk|pin)(?![a-z0-9]))"),
    ("key_material", r"-----BEGIN|ssh-(?:rsa|ed25519)|PRIVATE KEY"),
    ("unix_path", r"(?:^|[\s\"'=])/(?:etc|bin|sbin|usr|var|tmp|dev|proc|mnt|root|home)/"),
    ("windows_path", r"[A-Za-z]:\\|\\\\[A-Za-z0-9_.-]+\\"),
    ("command", r"(?i:(?<![a-z0-9])(?:system|popen|exec|busybox|iptables|wget|curl|telnetd|dropbear)(?![a-z0-9])|/bin/(?:sh|ash|bash|busybox)|sh -c|(?<![a-z0-9])nc -)"),
    ("config_key", r"(?i:(?<![a-z0-9])(?:bootcmd|firmware|serialnumber|mac(?:addr)?|ssid|wpa|psk|admin|root)(?![a-z0-9]))"),
    ("format_string", r"%(?:[0-9.*+-]*)(?:s|d|u|x|X|p|ll?[dux])"),
)


def default_string_pattern() -> str:
    """One alternation of DEFAULT_STRING_PATTERNS, for reporting and reuse."""
    return "|".join(f"(?:{pat})" for _, pat in DEFAULT_STRING_PATTERNS)


def classify_string(text: str) -> list[str]:
    """Which default pattern classes `text` matches (deterministic, regex only)."""
    return [name for name, pat in DEFAULT_STRING_PATTERNS if re.search(pat, text)]


# --------------------------------------------------------------------------
# Cost estimation (announced before a batch runs)
# --------------------------------------------------------------------------


def estimate_latency_seconds(tokens: int) -> float:
    """Interpolate the measured latency curve for a state of `tokens` tokens."""
    pts = MEASURED_LATENCY
    if tokens <= pts[0][0]:
        return MIN_REQUEST_SECONDS
    seconds = None
    for (t0, s0), (t1, s1) in zip(pts, pts[1:]):
        if tokens <= t1:
            frac = (tokens - t0) / (t1 - t0)
            seconds = s0 + frac * (s1 - s0)
            break
    if seconds is None:
        # Beyond the measured range: extrapolate on the last measured slope.
        (t0, s0), (t1, s1) = pts[-2], pts[-1]
        seconds = s1 + (tokens - t1) * (s1 - s0) / (t1 - t0)
    return round(max(MIN_REQUEST_SECONDS, seconds), 3)


def estimate_batch_seconds(item_count: int, tokens_per_item: int = MAX_EVIDENCE_TOKENS) -> float:
    """Expected wall-clock cost of scoring `item_count` items, one request each."""
    return round(max(0, item_count) * estimate_latency_seconds(tokens_per_item), 2)


